<section id="curso-ads" class="curso-section">
  <h2>Sobre o Curso: Análise e Desenvolvimento de Sistemas (ADS)</h2>

  <p>
    O curso de Análise e Desenvolvimento de Sistemas (ADS) forma profissionais capazes de projetar, implementar, testar e manter sistemas de software.
    O foco é prático e orientado a projetos, com disciplinas que abrangem lógica de programação, estruturas de dados, banco de dados, engenharia de software, redes, interfaces e metodologias ágeis.
  </p><br><br><br>

  <h3>Como funciona o curso</h3>
  <p>
    O curso combina aulas teóricas, atividades práticas e projetos integradores.  
    Os alunos trabalham em equipes para desenvolver sistemas reais, utilizam ferramentas e linguagens modernas e participam de atividades que simulam demandas do mercado.
  </p><br><br><br>

  <h3>Etapas do curso</h3>
  <ul>
    <li><strong>Fundamentos:</strong> matemática aplicada, lógica e computação.</li>
    <li><strong>Formação técnica:</strong> programação, banco de dados, estruturas de dados.</li>
    <li><strong>Projetos integradores:</strong> sistemas completos desenvolvidos em equipe.</li>
    <li><strong>Estágio:</strong> experiência profissional real.</li>
  </ul><br><br><br>

  <h3>Por que escolher este curso?</h3>
  <p>
    Alta demanda no mercado, crescimento profissional e oportunidades em desenvolvimento web, mobile, data science e mais.
    Ideal para quem resolve problemas e quer criar soluções digitais úteis.
  </p><br><br><br>

  <h3>Benefícios</h3>
  <ul>
    <li>Portfólio real durante o curso.</li>
    <li>Networking com empresas e professores.</li>
    <li>Possibilidade de estágios e empregos desde cedo.</li>
    <li>Base sólida para continuar estudando.</li>
  </ul><br><br><br>

  <h3>Vestibulinho da ETEC</h3>
  <p>
    Processo seletivo com inscrição online, prova objetiva e análise de requisitos.  
    Prepare-se com simulados e estude português, matemática e lógica.
  </p>

